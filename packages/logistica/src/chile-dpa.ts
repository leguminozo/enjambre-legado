/** Retorna las comunas ordenadas alfabéticamente para una región dada. */
export function getComunasPorRegion(region: string | null | undefined): readonly string[] {
  if (!region) return [];
  const trimmed = region.trim();
  const match = Object.keys(CHILE_COMUNAS_POR_REGION).find(
    (r) => r.toLowerCase() === trimmed.toLowerCase(),
  ) as ChileRegion | undefined;

  return match ? CHILE_COMUNAS_POR_REGION[match] : [];
}

/** Retorna la región a la cual pertenece una comuna dada. */
export function getRegionDeComuna(comuna: string | null | undefined): ChileRegion | null {
  if (!comuna) return null;
  const target = comuna.trim().toLowerCase();
  for (const [region, comunas] of Object.entries(CHILE_COMUNAS_POR_REGION)) {
    if (comunas.some((c) => c.toLowerCase() === target)) {
      return region as ChileRegion;
    }
  }
  return null;
}

/** Retorna el centroide geográfico aproximado de una región. */
export function getCentroideRegion(
  region: string | null | undefined,
): { lat: number; lng: number } | null {
  if (!region) return null;
  const trimmed = region.trim().toLowerCase();
  const info = CHILE_REGIONES_DPA.find((r) => r.nombre.toLowerCase() === trimmed);
  return info ? info.centroide : null;
}

/** Valida si una cadena es una región válida de Chile. */
export function isChileRegion(value: unknown): value is ChileRegion {
  return typeof value === 'string' && (CHILE_REGIONES as readonly string[]).includes(value);
}
