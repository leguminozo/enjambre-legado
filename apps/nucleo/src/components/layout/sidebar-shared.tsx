export function toNavItemDataFromItem(
  item: SidebarItem,
  badgeOverrides: Record<string, SidebarBadge>,
): SidebarNavItemData {
  const IconComp = LUCIDE_MAP[item.icon];
  return {
    key: item.key,
    label: item.label,
    icon: IconComp ? <IconComp size={18} /> : <span />,
    href: item.href,
    badge: badgeOverrides[item.key] ?? item.badge ?? null,
  };
}